import 'dart:io';
import 'package:drift/drift.dart';
import 'package:drift/native.dart';
import 'package:path/path.dart' as p;
import 'package:path_provider/path_provider.dart';

part 'app_database.g.dart'; // generated by build_runner

/// Local offline storage. Phase 1 caches the signed-in user's profile so the
/// Profile screen still opens without internet. Later phases add tables for
/// notes, flashcards, schedules and saved AI answers.
class CachedProfiles extends Table {
  TextColumn get userId => text()();
  TextColumn get json => text()();

  @override
  Set<Column> get primaryKey => {userId};
}

@DriftDatabase(tables: [CachedProfiles])
class AppDatabase extends _$AppDatabase {
  AppDatabase() : super(_openConnection());
  AppDatabase.forTesting(QueryExecutor e) : super(e);

  @override
  int get schemaVersion => 1;

  Future<void> saveProfile(String userId, String json) =>
      into(cachedProfiles).insertOnConflictUpdate(
          CachedProfilesCompanion.insert(userId: userId, json: json));

  Future<String?> loadProfile(String userId) async {
    final row = await (select(cachedProfiles)
          ..where((t) => t.userId.equals(userId)))
        .getSingleOrNull();
    return row?.json;
  }

  /// Wipes all locally cached user data (called on sign-out / account deletion).
  Future<void> clearAll() => delete(cachedProfiles).go();
}

LazyDatabase _openConnection() => LazyDatabase(() async {
      final dir = await getApplicationDocumentsDirectory();
      return NativeDatabase.createInBackground(
          File(p.join(dir.path, 'student_buddy.sqlite')));
    });
